/**
 * Utility lookup helper for fast matching by brand, model, variant, keyword, or body type
 */
export function findCarInWebsite(queryText) {
  if (!queryText || typeof queryText !== 'string') return null;
  const q = queryText.toLowerCase().trim();

  // Exact ID match
  const byId = websiteCars.find(c => c.id.toLowerCase() === q);
  if (byId) return byId;

  // Exact Model match
  const byModel = websiteCars.find(c => q.includes(c.model.toLowerCase()) || c.model.toLowerCase().includes(q));
  if (byModel) return byModel;

  // Brand + Model combination match
  const byBrandModel = websiteCars.find(c => {
    const combined = `${c.brand} ${c.model}`.toLowerCase();
    return q.includes(combined) || combined.includes(q);
  });
  if (byBrandModel) return byBrandModel;

  // Single word token match for distinct names (Fortuner, Creta, Seltos, Thar, Nexon, Spectre, Phantom, Pista, Huracan, 720S)
  const byToken = websiteCars.find(c => {
    const modelTokens = c.model.toLowerCase().split(/\s+/);
    return modelTokens.some(tok => tok.length > 2 && q.includes(tok));
  });

  return byToken || null;
}

export function searchWebsiteCars(queryText) {
  if (!queryText || typeof queryText !== 'string') return [];
  const q = queryText.toLowerCase().trim();
  return websiteCars.filter(c => {
    const full = `${c.brand} ${c.model} ${c.variant} ${c.fuelType} ${c.bodyType || ''} ${c.description}`.toLowerCase();
    return full.includes(q);
  });
}
