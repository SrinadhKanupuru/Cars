/**
 * Searches across both websiteCars and extendedCars
 */
export function findCarInComprehensiveDB(queryText) {
  if (!queryText || typeof queryText !== 'string') return null;
  const q = queryText.toLowerCase().trim();

  // Check alias list
  const byAlias = extendedCars.find(c => 
    c.aliases && c.aliases.some(alias => q.includes(alias) || alias.includes(q))
  );
  if (byAlias) return byAlias;

  // Check model match
  const byModel = extendedCars.find(c => 
    q.includes(c.model.toLowerCase()) || c.model.toLowerCase().includes(q)
  );
  if (byModel) return byModel;

  // Check brand match if specific brand
  const byBrand = extendedCars.find(c => {
    const full = `${c.brand} ${c.model}`.toLowerCase();
    return q.includes(full) || full.includes(q);
  });
  if (byBrand) return byBrand;

  return null;
}
