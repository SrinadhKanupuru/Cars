/**
 * Returns a fitting emoji or icon symbol for any brand name (known or newly created)
 */
export function getBrandEmojiOrIcon(brandName = '') {
  if (!brandName) return '🏎️';
  const name = brandName.toLowerCase();
  
  if (name.includes('ferrari')) return '🐎';
  if (name.includes('lambo')) return '🐂';
  if (name.includes('porsche')) return '⚡';
  if (name.includes('mclaren')) return '🏎️';
  if (name.includes('aston')) return '🪽';
  if (name.includes('bmw')) return '🔵';
  if (name.includes('mercedes') || name.includes('amg')) return '⭐';
  if (name.includes('audi')) return '🔴';
  if (name.includes('nissan') || name.includes('gt-r') || name.includes('gtr')) return '⚡';
  if (name.includes('bugatti')) return '💎';
  if (name.includes('koenigsegg')) return '🛡️';
  if (name.includes('rolls') || name.includes('royce')) return '👑';
  if (name.includes('pagani')) return '🌌';
  if (name.includes('maserati')) return '🔱';
  if (name.includes('bentley')) return '🦅';
  if (name.includes('lotus')) return '🪷';
  if (name.includes('toyota')) return '🚙';
  if (name.includes('hyundai')) return '🚗';
  if (name.includes('tesla')) return '⚡';
  if (name.includes('land rover') || name.includes('range rover')) return '🏔️';
  if (name.includes('jaguar')) return '🐆';
  if (name.includes('ford') || name.includes('mustang')) return '🐎';
  if (name.includes('chevrolet') || name.includes('corvette')) return '🏁';
  if (name.includes('dodge') || name.includes('viper') || name.includes('hellcat')) return '🐍';
  if (name.includes('alfa')) return '🍀';
  
  return '🏎️';
}

/**
 * Dynamically derives all brands by combining the active cars state and luxuryBrands catalogue.
 * Automatically synchronizes model counts and adds newly introduced brands instantly!
 */
export function getDynamicBrands(cars = []) {
  // Map of predefined luxury brands
  const knownBrandMap = new Map();
  luxuryBrands.forEach(b => {
    knownBrandMap.set(b.name.toLowerCase().trim(), b);
    knownBrandMap.set(b.id.toLowerCase().trim(), b);
  });

  // Extract all distinct brand names from the active cars list
  const distinctCarBrands = Array.from(
    new Set(
      cars
        .map(c => c.brand?.trim())
        .filter(Boolean)
    )
  );

  const brandCarMap = new Map();
  cars.forEach(car => {
    if (car.brand) {
      const key = car.brand.trim().toLowerCase();
      if (!brandCarMap.has(key)) {
        brandCarMap.set(key, []);
      }
      brandCarMap.get(key).push(car);
    }
  });

  const resultList = [];
  const processedKeys = new Set();

  // 1. Process brands present in the cars state first
  distinctCarBrands.forEach(brandName => {
    const key = brandName.toLowerCase();
    processedKeys.add(key);

    const matchingCars = brandCarMap.get(key) || [];
    const firstCar = matchingCars.find(c => c.images && c.images.length > 0);
    const carImage = firstCar?.images?.[0];

    const known = knownBrandMap.get(key);

    if (known) {
      resultList.push({
        ...known,
        modelsCount: matchingCars.length,
        image: carImage || known.image
      });
    } else {
      // Dynamic brand synthesized for newly added marques
      const slug = brandName.toLowerCase().replace(/[^a-z0-9]+/g, '-');
      resultList.push({
        id: slug,
        name: brandName,
        country: 'Global',
        founded: 2024,
        tagline: `${brandName} Elite Automotive Collection`,
        description: `Explore the exceptional craftsmanship, engineering, and performance credentials of ${brandName}.`,
        logo: getBrandEmojiOrIcon(brandName),
        badgeColor: '#e11d48',
        modelsCount: matchingCars.length,
      });
    }
  });

  // Return only brands that actually exist in the current website inventory
  return resultList;
}
